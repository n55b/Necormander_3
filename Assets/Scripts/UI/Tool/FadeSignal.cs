/// <summary>
/// 페이드 신호. "지금 이런 페이드가 벌어진다"는 순간의 이름이다.
///
/// 듣는 쪽이 둘로 갈리는데, 이유가 있다:
///
///   [화면 커튼] 세상에 하나뿐인 공유 자원이라 신호를 '듣지 않는다'.
///     문·포탈·FadeAction이 Fader.FullScreenFader.FadeOutIn(신호, 콜백)으로 직접 부른다.
///     '깜깜해진 순간'을 돌려받아야 그때 텔레포트/씬로드를 하기 때문에, 던지고 끝인 신호로는 안 된다.
///     이때 이 enum은 "커튼 반응 목록의 어느 줄 수치를 쓸지" 고르는 이름표 역할을 겸한다.
///     (커튼이 자기도 들으면 직접 호출 + 신호로 두 번 페이드된다.)
///
///   [그 외 UI·스프라이트 Fader] 이건 여럿이고 서로 독립적이라 '신호를 듣는다'.
///     반응 목록에 그 신호 줄만 적어두면 문을 지날 때 이 UI도 같이 사라진다 — 코드 0줄.
///     방송은 위의 FadeOutIn이 알아서 해준다. 그래서 부르는 쪽(문/포탈)은 누가 듣는지 몰라도 된다.
///
/// 신호를 추가하려면:
///   1. 아래에 한 줄 (맨 아래, 새 번호로)
///   2. 화면을 가리는 신호라면 ScreenFadeCanvas 프리팹의 Fader 반응 목록에도 같은 줄을 추가하고 수치를 정한다
///      ★ 2번을 빼먹으면 경고와 함께 맨 윗줄 수치로 돌아간다
///   3. 거는 쪽에서 fader.FadeOutIn(FadeSignal.새신호, ...) 또는 FadeAction에서 고른다
/// </summary>
public enum FadeSignal
{
    없음 = 0, // 어느 신호도 아님. 버튼/코드가 인자 없이 부를 때 쓰는 설정 줄.

    방이동 = 1,  // 문 통과(DoorController) / 전체지도에서 방 클릭(UIBasedMiniMap). 같은 층 안에서 방만 옮김.
    씬전환 = 2,  // 마을 → 던전 포탈(DungeonTeleporter). 씬을 통째로 로드.
    층이동 = 3,  // 층 클리어 후 다음 층(GameManager). 씬 재로드.

    // ★ 추가할 땐 반드시 '맨 아래에 새 번호로'.
    //    인스펙터엔 이름이 아니라 번호가 저장되기 때문에, 중간에 끼워넣으면 아래 것들이 전부 밀려서
    //    이미 세팅해둔 줄들이 조용히 딴 신호가 된다. 번호는 한 번 정하면 절대 안 바꾼다.
}
