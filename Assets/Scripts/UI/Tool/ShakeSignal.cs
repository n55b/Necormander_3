/// <summary>
/// 흔들림을 일으키는 신호 목록. 카메라와 UI 부품이 '같은 신호'를 듣되 각자 세기를 갖는다.
/// (그래서 "맞으면 체력바는 세게, 카메라는 살짝, 미니언바는 안 흔들림"이 코드 없이 나온다.
///  미니언바는 그냥 리시버를 안 붙이면 된다.)
///
/// ★ 신호를 함부로 늘리지 마라. 신호는 '드래그로 이을 수 없을 때'만 쓰는 도구다.
///   드래그가 되면 → 신호 쓰지 마라. Shaker의 Shake()를 그 자리 UnityEvent 슬롯에 드래그하면 끝이다.
///     예) 보스 등장할 때 화면 흔들기: BossRoomEvent의 On Boss Combat Start에 CameraShaker를 드래그.
///   드래그가 안 되면 → 그때 신호.
///     예) 플레이어는 런타임에 생기는데 체력바는 씬에 미리 있다 → 서로를 가리킬 수가 없다.
///
/// 신호를 정말 추가해야 한다면 두 단계 다 해야 함:
///   1. 아래 목록에 한 줄 추가 (맨 아래, 새 번호로) → 그 즉시 모든 Shaker의 드롭다운에 나타난다
///   2. 그 순간을 아는 곳에서 Signal.Fire(ShakeSignal.???); 한 줄
///      (기획자가 씬에서 직접 쏘고 싶으면 ShakeSender 컴포넌트를 쓰면 된다)
/// </summary>
public enum ShakeSignal
{
    없음 = 0, // 신호로 안 움직임. 드래그나 코드로만 부를 때.
    플레이어피격 = 1, // CharacterHealth가 피격 순간에 쏜다. 플레이어가 런타임 생성이라 드래그가 안 되는 케이스.
    적피격 = 2,      // 〃

    // ★ 신호를 추가할 땐 반드시 '맨 아래에 새 번호로' 추가할 것.
    //    인스펙터엔 이름이 아니라 번호가 저장되기 때문에, 중간에 끼워넣으면 아래 것들이 전부 밀려서
    //    이미 세팅해둔 컴포넌트들이 조용히 딴 신호를 듣게 된다. 번호는 한 번 정하면 절대 안 바꾼다.
    // 보스등장 = 3,
}
